"use client";

import { useEffect, useState } from "react";
import { Loader2, Sparkles } from "lucide-react";
import type { InsightsResult } from "@/lib/insights";
import { Button, Card, SectionTitle } from "@/components/ui";

export function Insights({ hasData }: { hasData: boolean }) {
  const [configured, setConfigured] = useState<boolean | null>(null);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [result, setResult] = useState<InsightsResult | null>(null);
  const [includeDemo, setIncludeDemo] = useState(false);

  useEffect(() => {
    fetch("/api/admin/insights")
      .then((r) => r.json())
      .then((b) => setConfigured(Boolean(b.configured)))
      .catch(() => setConfigured(false));
  }, []);

  async function analyze() {
    setBusy(true);
    setError(null);
    try {
      const res = await fetch("/api/admin/insights", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ includeDemo }),
      });
      const body = await res.json();
      if (!res.ok) throw new Error(body.error ?? "Analysis failed.");
      setResult(body as InsightsResult);
    } catch (e) {
      setError(e instanceof Error ? e.message : "Analysis failed.");
    } finally {
      setBusy(false);
    }
  }

  return (
    <Card className="p-5">
      <SectionTitle
        action={
          <div className="flex items-center gap-3">
            <label className="flex items-center gap-1.5 text-xs text-ink-mute">
              <input type="checkbox" checked={includeDemo} onChange={(e) => setIncludeDemo(e.target.checked)} />
              include demo data
            </label>
            <Button
              onClick={analyze}
              disabled={busy || configured === false || !hasData}
              size="sm"
              title={configured === false ? "Set ANTHROPIC_API_KEY to enable" : undefined}
            >
              {busy ? <Loader2 size={14} className="animate-spin" /> : <Sparkles size={14} />}
              Analyze Audience with AI
            </Button>
          </div>
        }
      >
        AI insights
      </SectionTitle>

      {configured === false && (
        <p className="text-sm text-ink-mute">
          AI analysis is off because no <code>ANTHROPIC_API_KEY</code> is set on the server. Everything
          else on this dashboard works without it.
        </p>
      )}
      {configured && !result && !error && !busy && (
        <p className="text-sm text-ink-mute">
          Reads the completed responses and returns challenges, requested capabilities, demo ideas and a
          suggested hands-on activity. Statistics are computed here; only the interpretation comes from
          the model.
        </p>
      )}
      {error && (
        <p className="text-sm text-danger" role="alert">
          {error}
        </p>
      )}

      {result && <InsightsView r={result} />}
    </Card>
  );
}

function InsightsView({ r }: { r: InsightsResult }) {
  const i = r.interpretation;
  const o = r.observed;
  return (
    <div className="mt-2 grid gap-6 lg:grid-cols-[minmax(0,280px)_1fr]">
      <div className="rounded-md border border-line bg-sunken p-4">
        <p className="text-xs font-semibold text-ink-soft">Observed — computed from data</p>
        <p className="mt-1 text-xs text-ink-mute">
          {r.sampleSize} completed responses{r.demoIncluded ? ", includes demo data" : ""}
        </p>
        <Fact label="Average proficiency" value={o.overview.avgProficiencyLabel} />
        <Fact label="Daily users" value={o.overview.dailyPct === null ? "—" : `${o.overview.dailyPct}%`} />
        <Fact label="Interested in automation" value={String(o.overview.automationInterested)} />
        <FactList label="Top wanted capabilities" items={o.topCapabilities} />
        <FactList label="Top limitations" items={o.topLimitations} />
        <FactList label="Task themes" items={o.taskThemes} />
      </div>

      <div>
        <p className="text-xs font-semibold text-warm">Interpretation — generated by AI</p>
        <p className="mt-2 text-[15px] leading-relaxed text-ink">{i.audienceSummary}</p>

        <div className="mt-5 grid gap-5 md:grid-cols-2">
          <List title="Common challenges" items={i.commonChallenges} />
          <List title="Most requested capabilities" items={i.requestedCapabilities} />
          <List title="Live demo opportunities" items={i.demoOpportunities} />
          <List title="Topics that deserve more time" items={i.topicsToEmphasize} />
        </div>

        <div className="mt-5 rounded-md border border-accent/30 bg-accent/5 p-4">
          <p className="text-xs font-semibold text-accent">Suggested hands-on activity · {i.handsOnActivity.durationMinutes} min</p>
          <p className="mt-1 font-semibold text-ink">{i.handsOnActivity.title}</p>
          <p className="mt-1 text-sm leading-relaxed text-ink-soft">{i.handsOnActivity.description}</p>
        </div>

        {i.caveats.length > 0 && (
          <ul className="mt-4 list-disc pl-5 text-xs text-ink-mute">
            {i.caveats.map((c, idx) => (
              <li key={idx}>{c}</li>
            ))}
          </ul>
        )}
      </div>
    </div>
  );
}

function Fact({ label, value }: { label: string; value: string }) {
  return (
    <div className="mt-3 flex items-baseline justify-between gap-2 text-sm">
      <span className="text-ink-mute">{label}</span>
      <span className="font-semibold text-ink">{value}</span>
    </div>
  );
}

function FactList({ label, items }: { label: string; items: Array<{ label: string; value: number }> }) {
  if (!items.length) return null;
  return (
    <div className="mt-3 text-sm">
      <p className="text-ink-mute">{label}</p>
      <ul className="mt-1">
        {items.map((i) => (
          <li key={i.label} className="flex justify-between gap-2">
            <span className="truncate text-ink-soft">{i.label}</span>
            <span className="font-semibold text-ink">{i.value}</span>
          </li>
        ))}
      </ul>
    </div>
  );
}

function List({ title, items }: { title: string; items: string[] }) {
  return (
    <div>
      <p className="text-sm font-semibold text-ink">{title}</p>
      <ul className="mt-1.5 flex flex-col gap-1.5 text-sm leading-relaxed text-ink-soft">
        {items.map((t, i) => (
          <li key={i} className="flex gap-2">
            <span className="mt-[9px] h-1 w-1 shrink-0 rounded-full bg-ink-mute" />
            <span>{t}</span>
          </li>
        ))}
      </ul>
    </div>
  );
}
